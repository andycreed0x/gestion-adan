test('simultaneous tabs share one expired snapshot refresh and background static concurrency is bounded', async ({ context, page }) => {
  let current = 0, maximum = 0
  const resources = new Set()
  context.on('request', (request) => {
    if (request.serviceWorker() && new URL(request.url()).pathname.startsWith('/_next/static/')) { resources.add(request); current++; maximum = Math.max(maximum, current) }
  })
  const finish = (request: any) => { if (resources.delete(request)) current-- }
  context.on('requestfinished', finish)
  context.on('requestfailed', finish)
  await login(page)
  await waitForPreparation(page)
  expect(maximum).toBeGreaterThan(0)
  expect(maximum).toBeLessThanOrEqual(4)
  const second = await context.newPage()
  await second.goto('/orders')
  await waitForSnapshot(second, 52)
  await control('clear-requests', {})
  await page.evaluate(async () => {
    const request = indexedDB.open('adan-orders-v1')
    const db: IDBDatabase = await new Promise((resolve) => { request.onsuccess = () => resolve(request.result) })
    await new Promise<void>((resolve) => {
      const tx = db.transaction('privateMetadata', 'readwrite')
      const records = tx.objectStore('privateMetadata').getAll()
      records.onsuccess = () => { for (const record of records.result) if (record.key?.[1] === 'freshness') tx.objectStore('privateMetadata').put({ ...record, value: 1 }) }
      tx.oncomplete = () => resolve()
    })
    db.close()
  })
  await Promise.all([page.evaluate(() => window.dispatchEvent(new Event('focus'))), second.evaluate(() => window.dispatchEvent(new Event('focus')))])
  await expect.poll(async () => (await control('requests')).filter((r) => r.path === '/rest/v1/repair_orders' && new URLSearchParams(r.query).has('limit')).length).toBe(2) // data batch + empty cursor batch
  await page.waitForTimeout(300)
  expect((await control('requests')).filter((r) => r.path === '/rest/v1/repair_orders' && new URLSearchParams(r.query).has('limit'))).toHaveLength(2)
})

