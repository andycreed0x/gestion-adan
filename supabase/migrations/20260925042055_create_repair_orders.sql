create extension if not exists pgcrypto;

create schema if not exists private;
revoke all on schema private from public;

do $$
begin
  create type public.repair_order_status as enum (
    'received',
    'in_progress',
    'ready',
    'picked_up',
    'cancelled'
  );
exception
  when duplicate_object then null;
end $$;

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null default '',
  role text not null default 'staff' check (role in ('staff', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.customers (
  id uuid primary key default gen_random_uuid(),
  full_name text not null check (char_length(trim(full_name)) > 0),
  address text not null default '',
  phone text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.repair_orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity (start with 9380) unique not null,
  customer_id uuid not null references public.customers (id) on delete restrict,
  equipment text not null check (char_length(trim(equipment)) > 0),
  accessories text not null default '',
  reported_fault text not null default '',
  resolution text not null default '',
  budget_cents bigint check (budget_cents is null or budget_cents >= 0),
  status public.repair_order_status not null default 'received',
  received_on date not null default current_date,
  picked_up_on date,
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint repair_orders_pickup_status_check check (
    (picked_up_on is null and status <> 'picked_up')
    or (picked_up_on is not null and status = 'picked_up')
  )
);

create table if not exists public.repair_order_events (
  id uuid primary key default gen_random_uuid(),
  repair_order_id uuid not null references public.repair_orders (id) on delete cascade,
  actor_id uuid references auth.users (id) on delete set null,
  event_type text not null check (event_type in ('created', 'updated', 'status_changed')),
  data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.repair_order_attachments (
  id uuid primary key default gen_random_uuid(),
  repair_order_id uuid not null references public.repair_orders (id) on delete cascade,
  storage_path text not null unique check (char_length(trim(storage_path)) > 0),
  file_name text not null check (char_length(trim(file_name)) > 0),
  mime_type text not null default 'application/octet-stream',
  size_bytes bigint not null check (size_bytes >= 0),
  uploaded_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists repair_orders_customer_id_idx on public.repair_orders (customer_id);
create index if not exists repair_orders_created_by_idx on public.repair_orders (created_by);
create index if not exists repair_orders_open_received_idx
  on public.repair_orders (received_on)
  where status not in ('picked_up', 'cancelled');
create index if not exists repair_order_events_order_id_idx on public.repair_order_events (repair_order_id, created_at desc);
create index if not exists repair_order_events_actor_id_idx on public.repair_order_events (actor_id);
create index if not exists repair_order_attachments_order_id_idx on public.repair_order_attachments (repair_order_id);
create index if not exists repair_order_attachments_uploaded_by_idx on public.repair_order_attachments (uploaded_by);
create index if not exists customers_name_idx on public.customers (lower(full_name));

create or replace function private.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = current_timestamp;
  return new;
end;
$$;

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'display_name', split_part(new.email, '@', 1), '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create or replace function private.log_repair_order_event()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := auth.uid();
begin
  if tg_op = 'INSERT' then
    insert into public.repair_order_events (repair_order_id, actor_id, event_type, data)
    values (
      new.id,
      actor,
      'created',
      jsonb_build_object('status', new.status, 'order_number', new.order_number)
    );
    return new;
  end if;

  insert into public.repair_order_events (repair_order_id, actor_id, event_type, data)
  values (
    new.id,
    actor,
    case when old.status is distinct from new.status then 'status_changed' else 'updated' end,
    jsonb_build_object(
      'previous_status', old.status,
      'status', new.status,
      'picked_up_on', new.picked_up_on,
      'budget_cents', new.budget_cents
    )
  );
  return new;
end;
$$;

